"""Generate the public legal pages in site/ from the markdown in docs/legal/.

Usage (from the repo root):  python docs/legal/build_pages.py

No dependencies. Handles the small markdown subset used in docs/legal/*.md.
What the public pages leave out:
  - blockquotes (the internal draft notes at the top);
  - everything from "**[pro]**" to the end of that paragraph or list item;
  - any "## Appendix" section and everything after it (internal Console answers).
Run it again after every change to the markdown and commit the HTML.
"""

from __future__ import annotations

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs" / "legal"
OUT = ROOT / "site"

PAGES = [
    # source, output, lang, <title>
    ("PRIVACY_POLICY.md", "privacy.html", "en", "Privacy Policy · ZnyprFit"),
    ("DATENSCHUTZ.md", "datenschutz.html", "de", "Datenschutzerklärung · ZnyprFit"),
    ("IMPRESSUM.md", "impressum.html", "de", "Impressum · ZnyprFit"),
]
LINKS = {
    "PRIVACY_POLICY.md": "privacy.html",
    "DATENSCHUTZ.md": "datenschutz.html",
    "IMPRESSUM.md": "impressum.html",
}
BACK = {"en": "Back to ZnyprFit", "de": "Zurück zu ZnyprFit"}


def strip_internal(md: str) -> str:
    md = md.replace("\r\n", "\n")
    md = re.split(r"^## Appendix", md, flags=re.M)[0]
    md = re.sub(r"\s*\*\*\[pro\]\*\*.*", "", md)  # rest of the line
    lines = [l for l in md.split("\n") if not l.lstrip().startswith(">")]
    md = "\n".join(lines).rstrip()
    md = re.sub(r"\n---\s*$", "", md)  # trailing rule left behind by the appendix cut
    return md + "\n"


def inline(text: str) -> str:
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"(?<![*\w])\*([^*]+)\*(?![*\w])", r"<em>\1</em>", out)

    def link(m: re.Match) -> str:
        label, href = m.group(1), m.group(2)
        href = LINKS.get(href, href)
        ext = href.startswith("http")
        rel = ' rel="noopener"' if ext else ""
        return f'<a href="{html.escape(href)}"{rel}>{label}</a>'

    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, out)
    return out


def slug(text: str) -> str:
    s = re.sub(r"<[^>]+>", "", text).lower()
    s = re.sub(r"[^a-z0-9äöüß]+", "-", s).strip("-")
    return s or "section"


def to_html(md: str) -> tuple[str, str]:
    """Return (h1 text, body html)."""
    blocks = re.split(r"\n\s*\n", md.strip())
    parts: list[str] = []
    h1 = "ZnyprFit"
    for block in blocks:
        lines = block.split("\n")
        first = lines[0]
        if first.startswith("# "):
            h1 = first[2:].strip()
            parts.append(f"<h1>{inline(h1)}</h1>")
            rest = "\n".join(lines[1:]).strip()
            if rest:
                parts.append(f"<p>{inline(rest)}</p>")
        elif first.startswith("## "):
            t = inline(first[3:].strip())
            parts.append(f'<h2 id="{slug(t)}">{t}</h2>')
            rest = "\n".join(lines[1:]).strip()
            if rest:
                parts.append(f"<p>{inline(rest)}</p>")
        elif first.strip() == "---":
            parts.append("<hr>")
        elif all(l.startswith("- ") for l in lines):
            items = "".join(f"<li>{inline(l[2:].strip())}</li>" for l in lines)
            parts.append(f"<ul>{items}</ul>")
        else:
            # Lines in a paragraph are kept as line breaks (addresses).
            parts.append("<p>" + "<br>\n".join(inline(l.strip()) for l in lines) + "</p>")
    return h1, "\n".join(parts)


TEMPLATE = """<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="dark light">
<meta name="robots" content="index,follow">
<title>{title}</title>
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="style.css">
</head>
<body>
<a class="skip" href="#main">{skip}</a>
<header class="bar">
  <div class="wrap bar-inner">
    <a class="brand" href="./">Znypr<span>Fit</span></a>
    <a class="back" href="./">{back}</a>
  </div>
</header>
<main id="main" class="wrap legal">
<!-- Generated by docs/legal/build_pages.py from docs/legal/{src}. Edit the markdown, not this file. -->
{body}
</main>
<footer class="foot">
  <div class="wrap foot-inner">
    <nav aria-label="Legal">
      <a href="privacy.html" hreflang="en">Privacy Policy</a>
      <a href="datenschutz.html" hreflang="de">Datenschutz</a>
      <a href="impressum.html" hreflang="de">Impressum</a>
    </nav>
    <p>ZnyprFit · no tracking, no cookies</p>
  </div>
</footer>
</body>
</html>
"""


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for src, out, lang, title in PAGES:
        md = strip_internal((SRC / src).read_text(encoding="utf-8"))
        _, body = to_html(md)
        page = TEMPLATE.format(
            lang=lang,
            title=html.escape(title),
            back=BACK[lang],
            skip="Skip to content" if lang == "en" else "Zum Inhalt",
            src=src,
            body=body,
        )
        (OUT / out).write_text(page, encoding="utf-8", newline="\n")
        print(f"wrote site/{out}")


if __name__ == "__main__":
    main()
